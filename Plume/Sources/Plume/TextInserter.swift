import AppKit
import ApplicationServices

/// Colle le texte là où est le curseur — ou dit qu'il n'y a pas de champ.
///
/// Si, à la fin de la dictée, le curseur n'est pas dans une zone
/// de texte, rien n'est collé et la dictée part dans l'historique de l'app.
///
/// Le collage passe par le presse-papiers + ⌘V (le seul moyen fiable dans
/// toutes les apps, y compris les sites web et Electron), et **le contenu
/// précédent du presse-papiers est remis** juste après. Le texte est marqué
/// « transitoire » pour que les gestionnaires de presse-papiers l'ignorent.
enum TextInserter {
    struct Target {
        let appName: String?
        let bundleID: String?
        /// `true` : champ de texte sûr ; `false` : sûrement pas de champ ;
        /// `nil` : on ne sait pas (l'app ne dit rien) → on colle quand même.
        let editable: Bool?
        let role: String?
        /// Le caractère juste avant le curseur est une lettre ou une ponctuation
        /// (pas une espace ni un retour à la ligne) : il faut une espace avant
        /// le texte collé, sinon deux dictées se collent (« 16h.Alors »).
        var needsLeadingSpace = false
    }

    static let textRoles: Set<String> = ["AXTextField", "AXTextArea", "AXComboBox", "AXSearchField", "AXSecureTextField"]
    /// Ce qui n'est sûrement pas un endroit où écrire.
    static let nonTextRoles: Set<String> = [
        "AXWindow", "AXApplication", "AXButton", "AXList", "AXOutline", "AXTable", "AXRow", "AXCell",
        "AXImage", "AXScrollArea", "AXSplitGroup", "AXToolbar", "AXMenu", "AXMenuBar", "AXMenuItem",
        "AXStaticText", "AXLink", "AXCheckBox", "AXRadioButton", "AXSlider", "AXPopUpButton",
        "AXTabGroup", "AXWebArea", "AXBrowser", "AXColumn", "AXDockItem", "AXDisclosureTriangle",
        // Un simple conteneur sans curseur de texte (vérifié dans Claude, 14/10) ;
        // une zone éditable web qui se déclare AXGroup est reconnue plus haut.
        "AXGroup",
    ]

    static func currentTarget() -> Target {
        let front = NSWorkspace.shared.frontmostApplication
        let appName = front?.localizedName
        let bundleID = front?.bundleIdentifier
        guard let pid = front?.processIdentifier else {
            return Target(appName: nil, bundleID: nil, editable: false, role: nil)
        }
        let app = AXUIElementCreateApplication(pid)
        AXUIElementSetMessagingTimeout(app, 0.4)
        var value: CFTypeRef?
        let err = AXUIElementCopyAttributeValue(app, kAXFocusedUIElementAttribute as CFString, &value)
        guard err == .success, let value, CFGetTypeID(value) == AXUIElementGetTypeID() else {
            // Le Finder sans fenêtre au premier plan (le bureau) : rien à écrire.
            let editable: Bool? = (bundleID == "com.apple.finder") ? false : nil
            return Target(appName: appName, bundleID: bundleID, editable: editable, role: nil)
        }
        let element = value as! AXUIElement
        let role = stringAttribute(element, kAXRoleAttribute)

        if let role, textRoles.contains(role) {
            return Target(appName: appName, bundleID: bundleID, editable: true, role: role,
                          needsLeadingSpace: characterBeforeCursorNeedsSpace(element))
        }
        // Zone éditable d'une page web (contenteditable) ou d'un éditeur maison :
        // elle a une sélection de texte, ou se déclare éditable.
        if boolAttribute(element, "AXEditable") == true || hasAttribute(element, kAXSelectedTextRangeAttribute)
            && isSettable(element, kAXValueAttribute) {
            return Target(appName: appName, bundleID: bundleID, editable: true, role: role,
                          needsLeadingSpace: characterBeforeCursorNeedsSpace(element))
        }
        if let role, nonTextRoles.contains(role) {
            return Target(appName: appName, bundleID: bundleID, editable: false, role: role)
        }
        return Target(appName: appName, bundleID: bundleID, editable: nil, role: role)
    }

    /// Colle `text` dans l'app au premier plan.
    @MainActor
    static func paste(_ text: String) {
        let pasteboard = NSPasteboard.general
        // Sauvegarde de tout le presse-papiers (tous les types de chaque élément).
        let saved: [[NSPasteboard.PasteboardType: Data]] = (pasteboard.pasteboardItems ?? []).map { item in
            var entry: [NSPasteboard.PasteboardType: Data] = [:]
            for type in item.types { if let data = item.data(forType: type) { entry[type] = data } }
            return entry
        }

        pasteboard.clearContents()
        let item = NSPasteboardItem()
        item.setString(text, forType: .string)
        item.setData(Data(), forType: NSPasteboard.PasteboardType("org.nspasteboard.TransientType"))
        item.setData(Data(), forType: NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType"))
        pasteboard.writeObjects([item])
        let ourChange = pasteboard.changeCount

        postCommandV()

        // L'app cible lit le presse-papiers pendant le ⌘V ; on attend un peu
        // avant de remettre l'ancien contenu (Electron peut être lent).
        DispatchQueue.main.asyncAfter(deadline: .now() + 0.8) {
            guard pasteboard.changeCount == ourChange else { return } // quelqu'un a copié entre-temps
            pasteboard.clearContents()
            guard !saved.isEmpty else { return }
            let items: [NSPasteboardItem] = saved.map { entry in
                let restored = NSPasteboardItem()
                for (type, data) in entry { restored.setData(data, forType: type) }
                return restored
            }
            pasteboard.writeObjects(items)
        }
    }

    private static func postCommandV() {
        let source = CGEventSource(stateID: .combinedSessionState)
        // Touche 9 = V (même emplacement en AZERTY et en QWERTY).
        let down = CGEvent(keyboardEventSource: source, virtualKey: 9, keyDown: true)
        let up = CGEvent(keyboardEventSource: source, virtualKey: 9, keyDown: false)
        down?.flags = .maskCommand
        up?.flags = .maskCommand
        down?.post(tap: .cghidEventTap)
        up?.post(tap: .cghidEventTap)
    }

    /// Les apps Electron (Claude, Slack, VS Code…) n'exposent leurs champs de
    /// texte qu'à la demande : on le leur demande dès qu'elles passent au
    /// premier plan, sinon on ne verrait jamais le champ où est le curseur.
    static func enableManualAccessibility(pid: pid_t) {
        let app = AXUIElementCreateApplication(pid)
        AXUIElementSetMessagingTimeout(app, 0.3)
        AXUIElementSetAttributeValue(app, "AXManualAccessibility" as CFString, kCFBooleanTrue)
    }

    /// Lit le caractère juste avant le curseur. En cas de doute → pas d'espace.
    private static func characterBeforeCursorNeedsSpace(_ e: AXUIElement) -> Bool {
        var rangeValue: CFTypeRef?
        guard AXUIElementCopyAttributeValue(e, kAXSelectedTextRangeAttribute as CFString, &rangeValue) == .success,
              let rangeValue, CFGetTypeID(rangeValue) == AXValueGetTypeID() else { return false }
        var range = CFRange()
        guard AXValueGetValue(rangeValue as! AXValue, .cfRange, &range), range.location > 0 else { return false }
        var previous = CFRange(location: range.location - 1, length: 1)
        guard let param = AXValueCreate(.cfRange, &previous) else { return false }
        var out: CFTypeRef?
        var char: String?
        if AXUIElementCopyParameterizedAttributeValue(e, kAXStringForRangeParameterizedAttribute as CFString, param, &out) == .success {
            char = out as? String
        } else if let value = stringAttribute(e, kAXValueAttribute) {
            let ns = value as NSString
            if range.location <= ns.length { char = ns.substring(with: NSRange(location: range.location - 1, length: 1)) }
        }
        guard let c = char?.unicodeScalars.first else { return false }
        if CharacterSet.whitespacesAndNewlines.contains(c) { return false }
        // Après une parenthèse ou un guillemet ouvrant, pas d'espace.
        if "([{«“'\"/-".unicodeScalars.contains(c) { return false }
        return true
    }

    // MARK: Lecture d'attributs

    private static func stringAttribute(_ e: AXUIElement, _ name: String) -> String? {
        var v: CFTypeRef?
        guard AXUIElementCopyAttributeValue(e, name as CFString, &v) == .success else { return nil }
        return v as? String
    }

    private static func boolAttribute(_ e: AXUIElement, _ name: String) -> Bool? {
        var v: CFTypeRef?
        guard AXUIElementCopyAttributeValue(e, name as CFString, &v) == .success else { return nil }
        return (v as? NSNumber)?.boolValue
    }

    private static func hasAttribute(_ e: AXUIElement, _ name: String) -> Bool {
        var v: CFTypeRef?
        return AXUIElementCopyAttributeValue(e, name as CFString, &v) == .success && v != nil
    }

    private static func isSettable(_ e: AXUIElement, _ name: String) -> Bool {
        var settable = DarwinBoolean(false)
        return AXUIElementIsAttributeSettable(e, name as CFString, &settable) == .success && settable.boolValue
    }
}
